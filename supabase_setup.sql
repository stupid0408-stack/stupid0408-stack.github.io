-- =====================================================================
-- 방명록(Guestbook) 테이블 설정 — 서버 함수 경유 버전
-- 구조: 브라우저 → Vercel 서버 함수(api/guestbook.js) → Supabase
--
-- 브라우저는 Supabase에 직접 접근하지 않습니다.
-- 서버 함수가 service_role 키로 접근하며, service_role 키는 RLS를 우회하므로
-- 공개(anon) 접근 정책은 만들지 않습니다. (= 외부에서 직접 테이블 접근 불가)
--
-- Supabase 대시보드 → SQL Editor → New query 에 붙여넣고 Run
-- =====================================================================

-- 1) 방명록 테이블 (없으면 생성)
create table if not exists public.guestbook (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 2 and 12),
  message     text not null check (char_length(message) between 1 and 100),
  created_at  timestamptz not null default now()
);

-- 2) 최신순 조회 성능용 인덱스
create index if not exists guestbook_created_at_idx
  on public.guestbook (created_at desc);

-- 3) Row Level Security 활성화
alter table public.guestbook enable row level security;

-- 4) 브라우저(anon) 직접 접근 정책 제거
--    이전에 브라우저 직접 연결로 실습하며 만들었던 공개 정책을 삭제합니다.
--    이제 접근은 서버 함수(service_role)만 수행하므로 공개 정책이 없어야 안전합니다.
drop policy if exists "guestbook public read"   on public.guestbook;
drop policy if exists "guestbook public insert" on public.guestbook;

-- 5) 브라우저(anon) 역할의 직접 권한 회수
--    (서버 함수의 service_role 키는 RLS/권한을 우회하므로 영향 없음)
revoke all   on table public.guestbook from anon;
revoke insert, select on table public.guestbook from anon;

