-- =====================================================================
-- 방명록(Guestbook) 테이블 설정 스크립트
-- Supabase 대시보드 → 왼쪽 메뉴 "SQL Editor" → New query 에 붙여넣고 Run
-- =====================================================================

-- 1) 방명록 테이블 생성
create table if not exists public.guestbook (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 40),
  message     text not null check (char_length(message) between 1 and 500),
  created_at  timestamptz not null default now()
);

-- 2) 최신순 조회 성능용 인덱스
create index if not exists guestbook_created_at_idx
  on public.guestbook (created_at desc);

-- 3) Row Level Security(행 수준 보안) 활성화
--    켜두면 아래에서 명시적으로 허용한 작업만 가능합니다.
alter table public.guestbook enable row level security;

-- 4) 정책: 누구나 "읽기(select)" 가능
drop policy if exists "guestbook public read" on public.guestbook;
create policy "guestbook public read"
  on public.guestbook
  for select
  to anon, authenticated
  using (true);

-- 5) 정책: 누구나 "작성(insert)" 가능
--    (수정/삭제 정책은 만들지 않았으므로 아무도 수정·삭제할 수 없음 = 안전)
drop policy if exists "guestbook public insert" on public.guestbook;
create policy "guestbook public insert"
  on public.guestbook
  for insert
  to anon, authenticated
  with check (
    char_length(name) between 1 and 40
    and char_length(message) between 1 and 500
  );

-- 6) 실시간(Realtime) 반영을 쓰려면 아래 한 줄도 실행
--    (다른 방문자가 남긴 메시지가 새로고침 없이 바로 보이게 함)
--    이미 등록돼 있으면 건너뛰도록 처리 (중복 실행해도 에러 안 남)
do $$
begin
  alter publication supabase_realtime add table public.guestbook;
exception
  when duplicate_object then null;
end $$;

-- =====================================================================
-- [추가] 테이블 접근 권한 부여 (GRANT)
-- "Automatically expose new tables"를 꺼둔 경우, 새 테이블은 기본적으로
-- 외부(anon/authenticated)에서 접근이 막혀 있어 아래 권한을 직접 부여해야 합니다.
-- 이것을 실행하지 않으면 "permission denied for table guestbook" 오류가 납니다.
-- (실제 접근 범위는 위에서 만든 RLS 정책이 다시 한 번 제어합니다.)
-- =====================================================================

-- 읽기(select) + 쓰기(insert) 권한 부여
grant select, insert on table public.guestbook to anon, authenticated;

-- id 자동증가(시퀀스) 사용 권한 부여
grant usage, select on all sequences in schema public to anon, authenticated;
